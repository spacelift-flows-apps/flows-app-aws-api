import { AppBlock, events } from "@slflows/sdk/v1";
import { AthenaClient, ListDataCatalogsCommand } from "@aws-sdk/client-athena";
import { STSClient, AssumeRoleCommand } from "@aws-sdk/client-sts";

const listDataCatalogs: AppBlock = {
  name: "List Data Catalogs",
  description: `Lists the data catalogs in the current Amazon Web Services account.`,
  inputs: {
    default: {
      config: {
        region: {
          name: "Region",
          description: "AWS region for this operation",
          type: "string",
          required: true,
        },
        assumeRoleArn: {
          name: "Assume Role ARN",
          description:
            "Optional IAM role ARN to assume before executing this operation. If provided, the block will use STS to assume this role and use the temporary credentials.",
          type: "string",
          required: false,
        },
        NextToken: {
          name: "Next Token",
          description:
            "A token generated by the Athena service that specifies where to continue pagination if a previous request was truncated.",
          type: "string",
          required: false,
        },
        MaxResults: {
          name: "Max Results",
          description:
            "Specifies the maximum number of data catalogs to return.",
          type: "number",
          required: false,
        },
        WorkGroup: {
          name: "Work Group",
          description: "The name of the workgroup.",
          type: "string",
          required: false,
        },
      },
      onEvent: async (input) => {
        const { region, assumeRoleArn, ...commandInput } =
          input.event.inputConfig;

        let credentials = {
          accessKeyId: input.app.config.accessKeyId,
          secretAccessKey: input.app.config.secretAccessKey,
          sessionToken: input.app.config.sessionToken,
        };

        // Determine credentials to use
        if (assumeRoleArn) {
          // Use STS to assume the specified role
          const stsClient = new STSClient({
            region: region,
            credentials: credentials,
            ...(input.app.config.endpoint && {
              endpoint: input.app.config.endpoint,
            }),
          });

          const assumeRoleCommand = new AssumeRoleCommand({
            RoleArn: assumeRoleArn,
            RoleSessionName: `flows-session-${Date.now()}`,
          });

          const assumeRoleResponse = await stsClient.send(assumeRoleCommand);
          credentials = {
            accessKeyId: assumeRoleResponse.Credentials!.AccessKeyId!,
            secretAccessKey: assumeRoleResponse.Credentials!.SecretAccessKey!,
            sessionToken: assumeRoleResponse.Credentials!.SessionToken!,
          };
        }

        const client = new AthenaClient({
          region: region,
          credentials: credentials,
          ...(input.app.config.endpoint && {
            endpoint: input.app.config.endpoint,
          }),
        });

        const command = new ListDataCatalogsCommand(commandInput as any);
        const response = await client.send(command);

        await events.emit(response || {});
      },
    },
  },
  outputs: {
    default: {
      name: "List Data Catalogs Result",
      description: "Result from ListDataCatalogs operation",
      possiblePrimaryParents: ["default"],
      type: {
        type: "object",
        properties: {
          DataCatalogsSummary: {
            type: "array",
            items: {
              type: "object",
              properties: {
                CatalogName: {
                  type: "string",
                },
                Type: {
                  type: "string",
                  enum: ["LAMBDA", "GLUE", "HIVE", "FEDERATED"],
                },
                Status: {
                  type: "string",
                  enum: [
                    "CREATE_IN_PROGRESS",
                    "CREATE_COMPLETE",
                    "CREATE_FAILED",
                    "CREATE_FAILED_CLEANUP_IN_PROGRESS",
                    "CREATE_FAILED_CLEANUP_COMPLETE",
                    "CREATE_FAILED_CLEANUP_FAILED",
                    "DELETE_IN_PROGRESS",
                    "DELETE_COMPLETE",
                    "DELETE_FAILED",
                  ],
                },
                ConnectionType: {
                  type: "string",
                  enum: [
                    "DYNAMODB",
                    "MYSQL",
                    "POSTGRESQL",
                    "REDSHIFT",
                    "ORACLE",
                    "SYNAPSE",
                    "SQLSERVER",
                    "DB2",
                    "OPENSEARCH",
                    "BIGQUERY",
                    "GOOGLECLOUDSTORAGE",
                    "HBASE",
                    "DOCUMENTDB",
                    "CMDB",
                    "TPCDS",
                    "TIMESTREAM",
                    "SAPHANA",
                    "SNOWFLAKE",
                    "DATALAKEGEN2",
                    "DB2AS400",
                  ],
                },
                Error: {
                  type: "string",
                },
              },
              additionalProperties: false,
            },
            description: "A summary list of data catalogs.",
          },
          NextToken: {
            type: "string",
            description:
              "A token generated by the Athena service that specifies where to continue pagination if a previous request was truncated.",
          },
        },
        additionalProperties: true,
      },
    },
  },
};

export default listDataCatalogs;
